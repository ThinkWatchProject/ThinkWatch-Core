//! 变成一次性交付 —— 客户端看到的是「卡很久，然后一下全出来」。所以这里
//! 是旁路的：字节照常流向客户端，同时喂它一份。
//!
//! 这一层刻意零业务依赖 —— 它不认识配置从哪来、数据存哪里、谁在调用，
//! 所以企业版和桌面版都直接用它。
//!
//! 以前这里还有订阅额度（`quota`）和正文留档（`bodies`）。两者只有桌面版
//! 在用，已经搬回 tw-gateway：只有一方在用的「共用件」，是第二个要改的
//! 地方，不是共用。

